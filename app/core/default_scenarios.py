def new_preset_scenarios(start_id: int | None) -> list[dict]:
    if start_id is None:
        return []

    presets = []
    for scenario_id, definition in enumerate(_NEW_SCENARIOS, start=start_id):
        preset = dict(definition)
        steps = preset.pop("steps")
        dialogue = preset.pop("dialogue")
        presets.append({
            **preset,
            "scenario_id": scenario_id,
            "ai_role": preset["call_target"],
            "scenario_image": None,
            "tts_voice_id": None,
            "script": [
                {"step": step, "ai_goal": goal, "hint": hint}
                for step, (goal, hint) in enumerate(steps, start=1)
            ],
            "example_dialogue": [
                {"speaker": "user" if index % 2 else "ai", "text": line}
                for index, line in enumerate(dialogue)
            ],
            "difficulties": ALL_DIFFICULTIES,
            "personalities": ALL_PERSONALITIES,
            "is_custom": False,
        })
    return presets
